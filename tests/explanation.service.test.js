const test = require("node:test");
const assert = require("node:assert/strict");
const {
  buildPortfolioDecision,
  buildPortfolioSummaryExplanation
} = require("../src/services/portfolio-decision.service");

function createPosition() {
  return {
    symbol: "TCS",
    metrics: { allocationPct: 12, profitLossPct: 80 },
    decisionInputs: {
      qualityScore: 8.8,
      technicalTrend: "healthy",
      momentum: "strong",
      sentiment: "positive"
    },
    sentiment: { sentiment: { label: "positive", score: 2 } },
    scoring: {
      finalScore: 8.8,
      normalizedScores: { technicalScore: 9, fundamentalScore: 9, sentimentScore: 10 },
      portfolioSignals: { signalCodes: [] }
    }
  };
}

test("portfolio decision owns the single deterministic position explanation", () => {
  const position = createPosition();
  const decision = buildPortfolioDecision(position);

  assert.equal(typeof decision.explanation, "string");
  assert.equal(decision.explanation.length > 0, true);
  assert.deepEqual(decision, buildPortfolioDecision(position));
  assert.doesNotMatch(decision.explanation, /current (sell|buy) signal/i);
  assert.doesNotMatch(decision.explanation, /sentiment is neutral/i);
});

test("portfolio summary narrative is factual and generated by the decision service", () => {
  const explanation = buildPortfolioSummaryExplanation({
    summary: { holdingsCount: 1, totalProfitLossPct: 12.4 },
    positions: [createPosition()]
  });

  assert.equal(
    explanation,
    "The portfolio contains 1 holding with a total return of +12.4%. The largest position is TCS at 12%."
  );
  assert.doesNotMatch(explanation, /recommend|sell|buy|\bhold\b/i);
});
